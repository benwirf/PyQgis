def geodesic_buffer_geom(x, y, radius):
    crs_wgs84 = QgsCoordinateReferenceSystem('epsg:4326')
    proj_string = 'PROJ4:+proj=aeqd +ellps=WGS84 +lat_0={} +lon_0={} +x_0=0 +y_0=0'.format(y, x)
    aeqd_crs = QgsCoordinateReferenceSystem(proj_string)
    ct = QgsCoordinateTransform(crs_wgs84, aeqd_crs, QgsProject.instance())
    center_pt = QgsPointXY(x, y)
    aeqd_center = ct.transform(center_pt)
    aeqd_buffer = QgsGeometry.fromPointXY(aeqd_center).buffer(radius, 90)#.asWkt()
    aeqd_buffer.transform(ct, Qgis.TransformDirection.Reverse)
    
    return aeqd_buffer

